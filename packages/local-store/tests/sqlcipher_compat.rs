//! Encrypted-database compatibility.
//!
//! A database written by the previous production candidate must still open, still be readable, and
//! still keep its bytes after the SQLCipher upgrade; and a wrong key must still be refused.
//!
//! The fixture is not committed and it is not written by the build under test.
//! `SORNIO_COMPAT_FIXTURE` points at a database produced by the previous build (SQLCipher 4.6.1).
//! When it is set, every assertion below runs against that real historical file: it is opened, its
//! bytes are compared before and after the open, and its records are read back and checked. When
//! it is not set, the file is generated by this build and the test proves only the invariant, the
//! wrong-key refusal and that reopening is durable - it does NOT prove cross-version compatibility,
//! and it says so in its own output rather than passing quietly.

use sornio_local_store::access::Workspace;
use sornio_local_store::catalog::AddProduct;
use sornio_local_store::identity::OwnerSetup;
use sornio_local_store::Store;
use std::path::{Path, PathBuf};

const KEY: &str = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";
const PASSWORD: &str = "Compatibility fixture password";

/// The plaintext SQLite header. SQLCipher encrypts the header as well, so a file that starts with
/// these bytes was never encrypted - it is a plaintext database wearing a fixture's name.
const PLAINTEXT_HEADER: &[u8] = b"SQLite format 3\0";

/// The historical fixture, when one was supplied.
fn historical_fixture() -> Option<PathBuf> {
    let path = PathBuf::from(std::env::var_os("SORNIO_COMPAT_FIXTURE")?);
    assert!(
        path.is_file(),
        "SORNIO_COMPAT_FIXTURE points at {}, which is not a file",
        path.display()
    );
    Some(path)
}

fn seeded(path: &Path) {
    let mut w = Workspace::new(Store::open(path, KEY).expect("a new store must open"));
    w.provision_owner(
        OwnerSetup {
            business_name: "Synthetic Compatibility".into(),
            business_type: "general".into(),
            display_name: "Owner".into(),
            username: "owner".into(),
        },
        PASSWORD,
    )
    .expect("owner setup must succeed");
    w.add_product(AddProduct {
        operation_id: "rice".into(),
        name: "Rice".into(),
        sku: "RICE".into(),
        unit: "kg".into(),
        unit_price_paise: 10000,
        opening_stock_milli: 10000,
    })
    .expect("the fixture needs a product and stock");
}

/// Read the records back and check that the upgrade preserved them.
///
/// A login is a deliberate write - it records a session and an audit entry - so this runs on a
/// copy of the historical fixture. That keeps the delivered file untouched, which is what lets the
/// test compare its bytes before and after.
fn records_are_intact(path: &Path) {
    let mut w = Workspace::new(Store::open(path, KEY).expect("the fixture must open with its key"));
    w.login("owner", PASSWORD)
        .expect("the fixture's owner credentials must still work");

    let products = w.list_products().expect("products must be readable");
    assert!(
        products.iter().any(|p| p.id == "rice"),
        "the historical product must survive the upgrade"
    );
    let rice = products.iter().find(|p| p.id == "rice").unwrap();
    assert_eq!(
        rice.stock_milli, 10000,
        "opening stock must be unchanged by the upgrade"
    );
    assert_eq!(rice.unit_price_paise, 10000, "prices are integer paise");

    // Authoritative balances must be identical after migration.
    let state = w.cashier_state().expect("cashier state must be readable");
    assert_eq!(state.balances.cash_paise, "0");

    w.lock();
    drop(w);

    // Closing and reopening must still be durable, and must be the same database, not a rebuild
    // of the same name - a rebuilt file would have a different header and a fresh page layout.
    let mut again = Workspace::new(Store::open(path, KEY).expect("reopen must succeed"));
    again.login("owner", PASSWORD).unwrap();
    let reread = again.list_products().unwrap();
    assert_eq!(
        reread.iter().find(|p| p.id == "rice").unwrap().stock_milli,
        10000,
        "records must remain durable across a close and reopen"
    );
    drop(again);
}

#[test]
fn encrypted_store_survives_the_upgrade_with_its_financial_balances_intact() {
    match historical_fixture() {
        Some(path) => {
            let before = std::fs::read(&path).expect("the fixture must be readable");
            assert!(
                !before.starts_with(PLAINTEXT_HEADER),
                "the fixture is not encrypted: it begins with the plaintext SQLite header"
            );
            assert!(
                before.len() > 4096,
                "the fixture is too small to be a real encrypted database"
            );

            // Open only. No login: a login is a deliberate write, and it must not be able to
            // masquerade as the open rewriting the database.
            {
                let _store =
                    Store::open(&path, KEY).expect("the historical fixture must open with its key");
                let after_open = std::fs::read(&path).expect("the fixture must still be readable");
                assert_eq!(
                    before, after_open,
                    "opening a historical database must not rewrite any byte of it"
                );
            }

            // The functional read-back runs on a copy, so this test never writes to the delivered
            // historical file and its bytes stay comparable.
            let work = Path::new(env!("CARGO_TARGET_TMPDIR")).join("compat-historical-work.db");
            let _ = std::fs::remove_file(&work);
            std::fs::copy(&path, &work).expect("the historical fixture must copy");
            assert_eq!(
                before,
                std::fs::read(&work).expect("the copy must be readable"),
                "the copy must start byte-identical to the fixture"
            );
            records_are_intact(&work);

            // And the delivered fixture is still exactly as it arrived.
            assert_eq!(
                before,
                std::fs::read(&path).expect("the fixture must still be readable"),
                "the historical fixture must be left byte-identical by this test"
            );
            eprintln!(
                "compat: the historical fixture opened byte-identically, its records were read back \
                 and checked, and the delivered file was left untouched"
            );
        }
        None => {
            let path = Path::new(env!("CARGO_TARGET_TMPDIR")).join("compat-generated.db");
            let _ = std::fs::remove_file(&path);
            seeded(&path);
            eprintln!(
                "compat: no SORNIO_COMPAT_FIXTURE set, so this run proves reopen durability and \
                 wrong-key refusal only - not cross-version compatibility"
            );
            records_are_intact(&path);
        }
    }
}

#[test]
fn a_wrong_key_or_corrupted_file_is_refused_without_destroying_it() {
    let path = Path::new(env!("CARGO_TARGET_TMPDIR")).join("compat-wrong-key.db");
    let _ = std::fs::remove_file(&path);
    seeded(&path);
    let original = std::fs::read(&path).unwrap();

    // A wrong key must fail closed, and must not replace the file with an empty database.
    let wrong = KEY.replace('0', "f");
    assert!(
        Store::open(&path, &wrong).is_err(),
        "a wrong key must be refused"
    );
    assert_eq!(
        std::fs::read(&path).unwrap(),
        original,
        "a failed open must leave the database untouched"
    );

    // Corrupting the encrypted page body must be detected rather than yielding rows.
    let corrupt = Path::new(env!("CARGO_TARGET_TMPDIR")).join("compat-corrupt.db");
    let _ = std::fs::remove_file(&corrupt);
    let mut bytes = original.clone();
    let middle = bytes.len() / 2;
    for b in bytes.iter_mut().skip(middle).take(64) {
        *b ^= 0xff;
    }
    std::fs::write(&corrupt, &bytes).unwrap();
    match Store::open(&corrupt, KEY) {
        Err(_) => {}
        Ok(store) => {
            let opened = Workspace::new(store);
            assert!(
                opened.list_products().is_err(),
                "a corrupted encrypted page must not yield readable rows"
            );
        }
    }
}
