#!/usr/bin/env node

/**
 * Retire phrases that no longer exist in the product.
 *
 * `npm run i18n:extract` rewrites `locales/en.json` from the source tree, so
 * deleting a screen drops its copy out of the English catalogue immediately.
 * The 22 generated catalogues are not so lucky: they are built by
 * `translate-catalog.mjs`, which only ever *adds* translations — so a retired
 * phrase lingers in every one of them, and `verify:i18n` fails with "22 unknown
 * phrases are present" on the next run.
 *
 * The tempting fix is to retranslate. That is the wrong one: it spends 22 × N
 * network calls to regenerate lines that were already reviewed, and it rewrites
 * files wholesale for a change that removed copy.
 *
 * So this does the only work there is to do: read the English catalogue, drop
 * from each locale every key the product no longer contains, and write the
 * result back deterministically (sorted, two-space, trailing newline) so the
 * diff is exactly the retired lines. Nothing is ever translated here.
 *
 * Usage:
 *   npm run i18n:extract && npm run i18n:prune
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const SOURCE_FILE = path.join(ROOT, 'locales', 'en.json');
const OUTPUT_DIRECTORY = path.join(ROOT, 'public', 'locales');

if (!fs.existsSync(SOURCE_FILE)) {
  console.error('locales/en.json is missing. Run: npm run i18n:extract');
  process.exit(1);
}

const source = JSON.parse(fs.readFileSync(SOURCE_FILE, 'utf8'));
const sourceKeys = new Set(Object.keys(source));
const files = fs
  .readdirSync(OUTPUT_DIRECTORY)
  .filter((entry) => entry.endsWith('.json'))
  .sort();

let removed = 0;
let untouched = 0;

for (const file of files) {
  const full = path.join(OUTPUT_DIRECTORY, file);
  const catalogue = JSON.parse(fs.readFileSync(full, 'utf8'));
  const retired = Object.keys(catalogue).filter((key) => !sourceKeys.has(key));

  if (retired.length === 0) {
    untouched += 1;
    continue;
  }

  // Deleted in place, not rebuilt: Bodo and Kashmiri are generated by a
  // different tool (`i18n:generate:low-resource`) and do not share the other
  // catalogues' key order. Re-sorting them here would turn nine retired lines
  // into a few hundred lines of pure reordering and bury the real change.
  for (const key of retired) delete catalogue[key];

  fs.writeFileSync(full, `${JSON.stringify(catalogue, null, 2)}\n`);
  removed += retired.length;
  console.log(`  ok    ${file}: retired ${retired.length} phrase(s)`);
  for (const key of retired.slice(0, 5)) console.log(`        - ${key.slice(0, 80)}`);
  if (retired.length > 5) console.log(`        - …and ${retired.length - 5} more`);
}

if (removed === 0) {
  console.log(`\nNothing to retire. ${untouched} catalogue(s) already match locales/en.json.`);
} else {
  console.log(
    `\nRetired ${removed} phrase(s) across ${files.length - untouched} catalogue(s). ` +
      `Run npm run verify:i18n to confirm all ${files.length} still cover all ${sourceKeys.size} phrases.`,
  );
}
